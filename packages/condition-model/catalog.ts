const RATE_MINUTES: PickerRange = {
  min: 5,
  max: 60,
  step: 5,
  unit: "minute",
};

function range(
  min: number,
  max: number,
  step: number,
  unit: PickerUnit,
): PickerRange {
  return { min, max, step, unit };
}

function rate(
  value: number,
  unit: PickerUnit,
  imperialQuantum?: { readonly value: number; readonly unit: PickerUnit },
): RatePicker {
  return {
    type: "rate",
    initialValue: null,
    quantum: { value, unit },
    ...(imperialQuantum === undefined ? {} : { imperialQuantum }),
    minutes: RATE_MINUTES,
  };
}

